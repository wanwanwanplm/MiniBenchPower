/* ADC 触发源: TIM3 1kHz (TRGO=更新事件)。降低自由连续采样的过高频率,
 * 使每半缓冲区(40样本=10次扫描)约 10ms 填满, taskADC 得以阻塞让出 CPU。 */
static void MX_TIM3_Init(void)
{
  __HAL_RCC_TIM3_CLK_ENABLE();

  htim3.Instance = TIM3;
  htim3.Init.Prescaler = 71;              /* APB1 定时器时钟 72MHz / 72 = 1MHz */
  htim3.Init.Period = 999;                /* 1MHz / 1000 = 1kHz 触发 */
  htim3.Init.CounterMode = TIM_COUNTERMODE_UP;
  htim3.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
  htim3.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_DISABLE;
  if (HAL_TIM_Base_Init(&htim3) != HAL_OK)
  {
    Error_Handler();
  }

  /* TRGO 输出"更新事件", 供 ADC 外部触发 */
  htim3.Instance->CR2 &= ~TIM_CR2_MMS;
  htim3.Instance->CR2 |= TIM_CR2_MMS_1;   /* MMS = 010 (Update) */

  HAL_TIM_Base_Start(&htim3);
}

